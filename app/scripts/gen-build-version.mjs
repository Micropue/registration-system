import { writeFileSync } from 'fs'
import { resolve, dirname } from 'path'
import { fileURLToPath } from 'url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const outPath = resolve(__dirname, '../src/config/build-version.ts')

const now = new Date()
const y = String(now.getFullYear())
const m = String(now.getMonth() + 1).padStart(2, '0')
const d = String(now.getDate()).padStart(2, '0')
const h = now.getHours()

let period
if (h < 6) period = 'A'
else if (h < 12) period = 'B'
else if (h < 18) period = 'C'
else period = 'D'

const version = `${y}${m}${d}${period}`

const content = `// Auto-generated by scripts/gen-build-version.mjs during build
export const BUILD_VERSION = '${version}'
`

writeFileSync(outPath, content, 'utf-8')
console.log(`Generated build version: ${version}`)
