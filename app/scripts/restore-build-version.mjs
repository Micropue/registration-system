import { writeFileSync } from 'fs'
import { resolve, dirname } from 'path'
import { fileURLToPath } from 'url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const outPath = resolve(__dirname, '../src/config/build-version.ts')

const content = `// Auto-generated by scripts/gen-build-version.mjs during build
export const BUILD_VERSION = 'dev'
`

writeFileSync(outPath, content, 'utf-8')
console.log('✓ Build version restored to dev')
